/**
 * 把别名合并进基础检索词。
 * @param {object} book
 * @param {string[]} baseQueries
 */
export function withAliases(book, baseQueries) {
  const aliases = SEARCH_ALIASES[book?.id] ?? [];
  const merged = [...aliases, ...baseQueries];
  return [...new Set(merged.filter(Boolean))];
}
