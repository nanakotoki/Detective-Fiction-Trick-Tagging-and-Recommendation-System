const COVER_DIR = new URL("../../covers/", import.meta.url);

/** 这部作品有没有本地封面 */
export function hasCover(id) {
  return Object.prototype.hasOwnProperty.call(COVER_ENTRIES, String(id));
}

/** 本地封面地址；没有封面时返回空串（调用方画占位块，不要产生 404 请求） */
export function coverUrl(id) {
  const key = String(id);
  if (!hasCover(key)) return "";
  const file = COVER_FILE_ALIAS[key] || key + ".webp";
  return new URL(file, COVER_DIR).href;
}

/** 封面出处（供详情页写「封面来源」一行）；没有封面时返回 null */
export function coverCredit(id) {
  const meta = COVER_ENTRIES[String(id)];
  if (!meta) return null;
  const [subjectId, year, code] = String(meta).split("|");
  const how = { S: "与本书评分取自同一条豆瓣条目", I: "豆瓣条目页 ISBN 与馆藏著录逐位相同", B: "上图书号 → 豆瓣条目页直达（ISBN 与所查一致）", P: "豆瓣条目页主图", T: "豆瓣题名与出版年均吻合", Y: "版本择优：与所收版本同年的一版", N: "版本择优：豆瓣上最新的一版", R: "微信读书：题名与作者都吻合（豆瓣条目页当时不可用）", A: "豆瓣题名是库内题名的前缀，且作者吻合（弱链接，副题被省）", W: "仅豆瓣题名吻合（弱链接）" }[code] || "豆瓣";
  return { subjectId, year, code, how, url: subjectId ? "https://book.douban.com/subject/" + subjectId + "/" : "" };
}

