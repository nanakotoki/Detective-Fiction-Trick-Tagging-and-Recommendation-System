/**
 * **原题名更正**（第 108 轮）。
 *
 * 起因：本轮用「原作名」批量比对时，`origtitle-crosscheck.mjs` 把珠海版《迷宫馆致命诱惑》
 * 判成了「新书候选」——它的原作名是 `迷路館の殺人`，而库内《迷宫馆事件》的原作名记的是
 * `迷宮館の殺人`，两边对不上。**这不是候选的问题，是库内的原题名写错了**：
 * 绫辻行人「馆」系列这一部是『**迷路館**の殺人』（迷路馆），`迷宮館` 是把「迷路」看成了「迷宮」。
 * 上图按作者枚举能查到日文原版著录「迷路館の殺人」（講談社 2009.11，ISBN 978-4062763974，477 页），
 * 珠海版《迷宫馆的诱惑》（2004）与《迷宫馆致命诱惑》（2011）的豆瓣条目页原作名也都是 `迷路館の殺人`。
 *
 * 为什么这类错危险：它**不会让任何闸门报错**，只会让判重工具把同一部作品的两种译名
 * 当成两部作品——正是本项目最怕的「查不出来的重复」。
 */
const RENAME_ORIGTITLE = [
  {
    title: '迷宫馆事件',
    author: '绫辻行人',
    from: '迷宮館の殺人',
    to: '迷路館の殺人',
    why:
      '**原作名更正（第 108 轮）**：本条原作名原记「迷宮館の殺人」，实为『**迷路館**の殺人』——上图按作者枚举可查到日文原版著录「迷路館の殺人」（講談社 2009.11，ISBN 978-4062763974，477 页），珠海版《迷宫馆的诱惑》（2004）与《迷宫馆致命诱惑》（2011）的豆瓣条目页原作名也都是 `迷路館の殺人`。原写法会让判重工具把这一部的两种译名当成两部作品，故更正。',
  },
];

/**
 * **按条目的系列名补记**（第 108 轮）。
 *
 * `RENAME_SERIES` 处理的是「同一个系列名的两种写法」的全局归一，这里不是那种情形：
 * 《暗黑杀人耳语》当时按「馆藏丛编项只著录了年份、不代拟系列名」的口径记了「非系列」，
 * 那是**当时没有依据**；本轮从豆瓣条目页的出版方简介拿到了依据——作者继「馆」系列之后
 * 推出「**耳语**」系列，且同社同年（吉林出版集团 2012）另有《黄昏杀人耳语》《绯色杀人耳语》。
 * 所以这里按**条目**改，不动其他记作「非系列」的书。
 */
const RENAME_SERIES_BY_TITLE = [
  {
    title: '暗黑杀人耳语',
    author: '绫辻行人',
    from: '非系列',
    to: '耳语系列',
    why:
      '**系列名补记（第 108 轮）**：本条原记 `series` 为「非系列」（当时馆藏丛编项只著录年份，按「不代拟系列名」的口径留空）。本轮据豆瓣条目页出版方简介——作者继「馆」系列后推出「**耳语**」系列——以及同社同年（吉林出版集团 2012）出版的《黄昏杀人耳语》《绯色杀人耳语》同属该系列，把 `series` 补记为「耳语系列」。',
  },
];

const APPLY = process.argv.includes('--apply');
const files = readdirSync('data/books').filter((x) => x.endsWith('.json') && !x.startsWith('_'));
const store = new Map();
for (const f of files) store.set(f, JSON.parse(readFileSync(`data/books/${f}`, 'utf8')));

let changed = 0;
const touched = new Set();
for (const p of PLAN) {
  let hit = null;
  let file = null;
  for (const [f, arr] of store) {
    const b = arr.find((x) => x.title === p.title && x.author === p.author);
    if (b) {
      hit = b;
      file = f;
      break;
    }
  }
  if (!hit) {
    console.log(`✗ 找不到《${p.title}》/${p.author}`);
    continue;
  }
  if ((hit.alternateTitles || []).includes(p.alias)) {
    console.log(`· 《${p.title}》已有别名「${p.alias}」，跳过`);
    continue;
  }
  hit.alternateTitles = [...(hit.alternateTitles || []), p.alias];
  const mark = MARK_OF(p.round || 76);
  if (!hit.verification.source.includes(mark)) hit.verification.source += ` ${mark}：${p.why}`;
  touched.add(file);
  changed += 1;
  console.log(`✓ 《${p.title}》(${file}) → 别名 +「${p.alias}」`);
}

console.log(`\n将登记 ${changed} 条别名${APPLY ? '' : '（干跑，未落盘）'}`);

/** 作者名归一 */
let renamed = 0;
for (const r of RENAME_AUTHOR) {
  for (const [f, arr] of store) {
    const b = arr.find((x) => x.title === r.title && x.author === r.from);
    if (!b) continue;
    b.author = r.to;
    if (Array.isArray(b.authors)) b.authors = b.authors.map((n) => (n === r.from ? r.to : n));
    b.verification.source +=
      ` **作者名归一（第 80 轮）**：本条原记作者为「${r.from}」，与库内其余条目写法（「${r.to}」）不一致，已统一；` +
      '否则同一位作者会在作者页上被拆成两个人。';
    touched.add(f);
    renamed += 1;
    console.log(`✓ 《${r.title}》作者「${r.from}」→「${r.to}」`);
  }
}
console.log(`将归一 ${renamed} 条作者名`);

/** 系列名归一 */
let rs = 0;
for (const r of RENAME_SERIES) {
  for (const [f, arr] of store) {
    for (const b of arr) {
      if (b.series !== r.from) continue;
      b.series = r.to;
      b.verification.source +=
        ` **系列名归一（第 87 轮）**：本条原记系列为「${r.from}」，与库内同一系列的多数写法（「${r.to}」）不一致，已统一；` +
        '否则同一位侦探的作品会被算成两个系列。';
      touched.add(f);
      rs += 1;
    }
  }
}
console.log(`将归一 ${rs} 条系列名`);

/** 主角名归一 */
let rd = 0;
for (const r of RENAME_DETECTIVE) {
  for (const [f, arr] of store) {
    for (const b of arr) {
      if (b.detective !== r.from) continue;
      b.detective = r.to;
      b.verification.source +=
        ` **主角名归一（第 87 轮）**：本条原记主角为「${r.from}」，与库内同一人物的多数写法（「${r.to}」）不一致，已统一。`;
      touched.add(f);
      rd += 1;
    }
  }
}
console.log(`将归一 ${rd} 条主角名`);

/** 原题名更正（第 108 轮） */
let ro = 0;
for (const r of RENAME_ORIGTITLE) {
  for (const [f, arr] of store) {
    const b = arr.find((x) => x.title === r.title && x.author === r.author);
    if (!b) continue;
    if (b.originalTitle !== r.from) {
      console.log(`· 《${r.title}》原作名现为「${b.originalTitle || '（空）'}」，与待更正值「${r.from}」不符，跳过`);
      continue;
    }
    b.originalTitle = r.to;
    b.verification.source += ` ${r.why}`;
    touched.add(f);
    ro += 1;
    console.log(`✓ 《${r.title}》原作名「${r.from}」→「${r.to}」`);
  }
}
console.log(`将更正 ${ro} 条原题名`);

/** 按条目的系列名补记（第 108 轮） */
let rst = 0;
for (const r of RENAME_SERIES_BY_TITLE) {
  for (const [f, arr] of store) {
    const b = arr.find((x) => x.title === r.title && x.author === r.author);
    if (!b) continue;
    if (b.series !== r.from) {
      console.log(`· 《${r.title}》系列现为「${b.series || '（空）'}」，与待改值「${r.from}」不符，跳过`);
      continue;
    }
    b.series = r.to;
    b.verification.source += ` ${r.why}`;
    touched.add(f);
    rst += 1;
    console.log(`✓ 《${r.title}》系列「${r.from}」→「${r.to}」`);
  }
}
console.log(`将补记 ${rst} 条系列名`);

if (APPLY && (changed || renamed || rs || rd || ro || rst)) {
  for (const f of touched) writeFileSync(`data/books/${f}`, JSON.stringify(store.get(f), null, 2) + '\n', 'utf8');
  console.log(`已写入 ${touched.size} 个文件`);
}
